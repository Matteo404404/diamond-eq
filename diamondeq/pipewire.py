"""PipeWire integration: output discovery and the EQ filter process.

Each equalised output gets its own `pipewire -c <conf>` process running a
filter-chain of exact biquads. The filter is a WirePlumber "smart filter"
bound to that one output: audio going to the output is routed through it
automatically, the output stays the default device, and stopping the process
removes the EQ without touching any stream.
"""
from __future__ import annotations

import ctypes
import hashlib
import json
import os
import re
import signal
import subprocess
from pathlib import Path

from .biquad import HIGH_SHELF, LOW_SHELF, PEAKING, Filter

NODE_PREFIX = "diamondeq."
_LABELS = {PEAKING: "bq_peaking", LOW_SHELF: "bq_lowshelf", HIGH_SHELF: "bq_highshelf"}


def runtime_dir() -> Path:
    d = Path(os.environ.get("XDG_RUNTIME_DIR", "/tmp")) / "diamondeq"
    d.mkdir(parents=True, exist_ok=True)
    return d


def list_sinks() -> list[dict]:
    """Real output devices (our own filter sinks are left out)."""
    try:
        raw = subprocess.run(["pactl", "-f", "json", "list", "sinks"], capture_output=True, text=True,
                             timeout=10, check=True).stdout
        sinks = json.loads(raw)
    except (OSError, subprocess.SubprocessError, ValueError):
        return []
    try:
        default = subprocess.run(["pactl", "get-default-sink"], capture_output=True, text=True,
                                 timeout=10).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        default = ""
    out = []
    for s in sinks:
        name = s.get("name", "")
        props = s.get("properties", {})
        if name.startswith(NODE_PREFIX) or props.get("node.name", "").startswith(NODE_PREFIX):
            continue
        ports = s.get("ports", [])
        active = next((p for p in ports if p.get("name") == s.get("active_port")), None)
        mac = props.get("api.bluez5.address", "")
        if not mac and (m := re.match(r"bluez_output\.((?:[0-9A-Fa-f]{2}_){5}[0-9A-Fa-f]{2})", name)):
            mac = m.group(1).replace("_", ":")
        if mac:
            kind, label = "bluetooth", s.get("description") or props.get("device.description", name)
        else:
            kind = "usb" if props.get("device.bus") == "usb" else "builtin"
            label = s.get("description") or name
        out.append({
            "key": f"bt:{mac.upper()}" if mac else f"node:{name}",
            "node": name,
            "label": label,
            "kind": kind,
            "mac": mac.upper(),
            "default": name == default,
            "available": not active or active.get("availability") != "not available",
        })
    return out


def _slug(sink_node: str) -> str:
    return hashlib.sha1(sink_node.encode()).hexdigest()[:10]


def filter_node_name(sink_node: str) -> str:
    return NODE_PREFIX + _slug(sink_node)


def config_text(sink_node: str, title: str, filters: list[Filter], preamp_db: float) -> str:
    """PipeWire config for one EQ filter bound to sink_node."""
    nodes = ['{ type = builtin name = preamp label = linear control = { "Mult" = %.8f "Add" = 0.0 } }'
             % (10.0 ** (preamp_db / 20.0))]
    for i, f in enumerate(filters, 1):
        nodes.append('{ type = builtin name = band%d label = %s control = { "Freq" = %.4f "Q" = %.6f "Gain" = %.4f } }'
                     % (i, _LABELS[f.type], f.fc, f.q, f.gain))
    chain = ["preamp"] + [f"band{i}" for i in range(1, len(filters) + 1)]
    links = ['{ output = "%s:Out" input = "%s:In" }' % (a, b) for a, b in zip(chain, chain[1:])]
    name = filter_node_name(sink_node)
    desc = json.dumps(f"Diamond EQ: {title}")
    return f"""# Generated by diamondeq. Do not edit; it is rewritten on every change.
context.properties = {{ log.level = 0 }}
context.spa-libs = {{
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}}
context.modules = [
    {{ name = libpipewire-module-rt args = {{ nice.level = -11 }} flags = [ ifexists nofail ] }}
    {{ name = libpipewire-module-protocol-native }}
    {{ name = libpipewire-module-client-node }}
    {{ name = libpipewire-module-adapter }}
    {{ name = libpipewire-module-filter-chain
        args = {{
            node.description = {desc}
            media.name       = {desc}
            filter.graph = {{
                nodes = [
                    {chr(10).join(' ' * 20 + n for n in nodes).strip()}
                ]
                links = [
                    {chr(10).join(' ' * 20 + ln for ln in links).strip()}
                ]
                inputs  = [ "preamp:In" ]
                outputs = [ "{chain[-1]}:Out" ]
            }}
            audio.channels = 2
            audio.position = [ FL FR ]
            capture.props = {{
                node.name   = "{name}"
                media.class = Audio/Sink
                filter.smart = true
                filter.smart.name = "{name}"
                filter.smart.target = {{ node.name = {json.dumps(sink_node)} }}
            }}
            playback.props = {{
                node.name    = "{name}.out"
                node.passive = true
                stream.dont-remix = true
            }}
        }}
    }}
]
"""


def signature(title: str, filters: list[Filter], preamp_db: float) -> str:
    """Identity of a filter setup; a running filter is restarted when it changes."""
    return json.dumps([title, [f.to_dict() for f in filters], round(preamp_db, 3)])


def _die_with_parent() -> None:
    # PR_SET_PDEATHSIG: the kernel terminates the filter if the service dies,
    # so a crashed or killed service never leaves an EQ running unmanaged.
    ctypes.CDLL("libc.so.6", use_errno=True).prctl(1, signal.SIGTERM)


class FilterProcess:
    """One running EQ filter."""

    def __init__(self, sink_node: str, title: str, filters: list[Filter], preamp_db: float):
        self.sink_node = sink_node
        self.signature = signature(title, filters, preamp_db)
        self.conf = runtime_dir() / f"{_slug(sink_node)}.conf"
        self.conf.write_text(config_text(sink_node, title, filters, preamp_db))
        self.proc = subprocess.Popen(["pipewire", "-c", str(self.conf)], stdin=subprocess.DEVNULL,
                                     stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, text=True,
                                     preexec_fn=_die_with_parent)

    def alive(self) -> bool:
        return self.proc.poll() is None

    def error(self) -> str:
        if self.alive() or not self.proc.stderr:
            return ""
        return (self.proc.stderr.read() or "").strip()[-400:]

    def stop(self) -> None:
        if self.alive():
            self.proc.terminate()
            try:
                self.proc.wait(timeout=3)
            except subprocess.TimeoutExpired:
                self.proc.kill()
                self.proc.wait(timeout=3)
        self.conf.unlink(missing_ok=True)
